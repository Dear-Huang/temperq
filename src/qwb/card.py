"""Model card: README.md with YAML front matter (SPEC §11, §15).

The package manifest is the source of truth; the card is generated from it so
HF/GitHub show the same facts. The share site parses only the front matter
(plain YAML, no code), and treats every value as untrusted text.
"""

from __future__ import annotations

import html
import re

import yaml

FM = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)

# fields the site shows; anything else in the front matter is ignored
SITE_FIELDS = {
    "qwb_version": str, "task": str, "market": str, "template": str, "base_model": str,
    "base_model_revision": str, "seeds": list, "data_snapshot_id": str,
    "data_license": str, "custom_code": bool, "includes_data": bool,
    "reproducibility": dict, "deviations_from_default": list, "pretrain_contamination": str,
    "license": str, "tags": list,
    "run_id": str, "model_version": str, "prediction_version": str, "evaluation_id": str, "protocol_id": str,
    "evidence_source": str,
}
MAX_STR = 300
OPTIONAL_SITE_FIELDS = {"run_id", "model_version", "prediction_version", "evaluation_id", "protocol_id", "evidence_source"}
MAX_LIST = 50
# phrases the site's content check flags (SPEC §15); not a judgement of model quality
FLAG_PATTERNS = [r"保证收益", r"稳赚", r"年化\s*\d{2,}\s*%", r"荐股", r"加\s*(微信|v信|vx|qq)",
                 r"付费群", r"guaranteed\s+returns?", r"risk[- ]free"]


def render(manifest: dict, task: dict, metrics: dict, repro: dict, extra_md: str = "") -> str:
    fm = {
        "license": manifest["licenses"]["model"],
        "tags": ["temperq", "quant", task["market"], task["template"]],
        "qwb_version": "0.0.1",
        "task": task["name"], "market": task["market"], "template": task["template"],
        "base_model": manifest["base_model"]["name"],
        "base_model_revision": str(manifest["base_model"]["version"]),
        "seeds": manifest["train_config"]["seeds"],
        "data_snapshot_id": manifest.get("data_snapshot_id", ""),
        "data_license": manifest["licenses"]["data"],
        "custom_code": bool(manifest.get("custom_code", False)),
        "includes_data": bool(manifest.get("includes_data", False)),
        "reproducibility": {"R1": bool(repro.get("R1")), "R2": bool(repro.get("R2")),
                            "checked_on": "author machine"},
        "deviations_from_default": manifest.get("deviations_from_default", []),
    }
    fm.update({key: metrics[key] for key in OPTIONAL_SITE_FIELDS if metrics.get(key) is not None})
    ic = metrics["ic"]
    rows = "\n".join(
        f"| {k} | {v['final_test']['mean']:+.4f} | {v['final_test']['t']:.2f} |"
        for k, v in ic.items() if not k.startswith("lgbm_seed"))
    body = f"""# {manifest['name']}

Generated by TemperQ from the package manifest. Numbers are the tool's standard report;
author notes are separate and unverified.

## Task
`{task['name']}` · {task['market']} · {task['template']} · label
open[t+{task['label']['start']['day']}] → open[t+{task['label']['end']['day']}]

## Standard report (final test {', '.join(map(str, metrics['final_test_years']))}, daily rank IC, NW lag {metrics['nw_lag']})

| signal | IC | t |
|---|---|---|
{rows}

Shuffle null: {metrics['shuffle_null_mean']:+.4f} ± {metrics['shuffle_null_sd']:.4f}.
Seed rank correlation {sum(metrics['seed_pred_rank_corr']) / max(len(metrics['seed_pred_rank_corr']), 1):.3f}.

## Reproducibility
R1 (loads) {fm['reproducibility']['R1']}, R2 (consistency sample) {fm['reproducibility']['R2']},
checked on the author's machine. R3 needs the same data snapshot (`{fm['data_snapshot_id']}`),
which is not distributed.

## Data
Not included. Recipe: `recipe.yaml`. Data license: {fm['data_license']}.

## Evidence boundary
Ranking ability under the stated data and assumptions. No costs, no execution
constraints, not a return forecast, not investment advice.
"""
    return "---\n" + yaml.safe_dump(fm, allow_unicode=True, sort_keys=False) + "---\n\n" + body + extra_md


def _clean(v, typ):
    if typ is str:
        return html.escape(str(v)[:MAX_STR])
    if typ is bool:
        return v if isinstance(v, bool) else None
    if typ is list:
        return [html.escape(str(x)[:MAX_STR]) for x in v[:MAX_LIST]] if isinstance(v, list) else None
    if typ is dict:
        return {html.escape(str(k)[:50]): html.escape(str(x)[:MAX_STR])
                for k, x in list(v.items())[:MAX_LIST]} if isinstance(v, dict) else None
    return None


def parse(readme: str) -> dict:
    """Front matter -> sanitized site fields. Never executes anything from the repo."""
    m = FM.match(readme)
    if not m:
        return {"ok": False, "error": "no YAML front matter", "fields": {}, "flags": []}
    try:
        data = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as e:
        return {"ok": False, "error": f"bad YAML: {type(e).__name__}", "fields": {}, "flags": []}
    if not isinstance(data, dict):
        return {"ok": False, "error": "front matter is not a mapping", "fields": {}, "flags": []}
    fields, missing = {}, []
    for k, typ in SITE_FIELDS.items():
        if k not in data:
            if k not in OPTIONAL_SITE_FIELDS:
                missing.append(k)
            continue
        v = _clean(data[k], typ)
        if v is not None:
            fields[k] = v
    flags = [p for p in FLAG_PATTERNS if re.search(p, readme, re.I)]
    return {"ok": True, "fields": fields, "missing": missing, "flags": flags,
            "is_qwb": "qwb_version" in fields}
